export interface PageSeo {
  title: string;
  description: string;
  /** H1 text. `h1Suffix` renders as a smaller second line inside the same H1. */
  h1: string;
  h1Suffix?: string;
  /** Path of a 1200x630 JPG in /public (generated by scripts/generate-og.mjs). Default: /og-image.jpg */
  ogImage?: string;
  ogType?: 'website' | 'profile';
  noindex?: boolean;
}

const BRANDS = ['AadiVed Yoga & Wellness', 'AadiVed Yoga', 'AadiVed'];

/** Build "[head] | [brand]" and use the longest brand that keeps the title within 60 characters. */
export function title(head: string, brands: string[] = BRANDS): string {
  const brand = brands.find((b) => `${head} | ${b}`.length <= 60) ?? brands[brands.length - 1];
  return `${head} | ${brand}`;
}


// Titles: 50 to 60 characters, primary keyword first, brand last. Service pages use
// "[Topic] in Hinjawadi, Pune | brand" and `title()` picks the longest brand that still fits in 60.
// Descriptions: 140 to 160 characters. No em dashes.
// `scripts/seo-audit.mjs` checks all of this against the built HTML.


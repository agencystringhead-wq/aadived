/** SEO for a path, with or without a trailing slash. */
export function getSeo(path: string): PageSeo {
  const key = path.endsWith('/') ? path : `${path}/`;
  const s = seo[key];
  if (!s) throw new Error(`No SEO entry for ${key}. Add it to src/data/seo.ts.`);
  return s;
}
